<?php
// 关卡 5.12 极简教学：门铃与岗位卡（彻底拆解回调数组机制）

// ==================== 1. 基础认知：函数可以存进数组里 ====================
// 在 PHP 中，数组不仅能存数字和字符串，还能存“一段准备执行的动作（函数）”！
$actions = [];

// 在 3 号挂钩上，挂一张卡片：“迎宾接待”
$actions[3] = function ($name) {
    echo "【3号卡片执行】欢迎光临大饭店，$name 先生请进！\n";
};

// 在 4 号挂钩上，挂一张卡片：“端茶送水”
$actions[4] = function ($name) {
    echo "【4号卡片执行】给 $name 先生倒了一杯大红袍！\n";
};

echo "--- 演示根据号码牌执行对应动作 ---\n";
$target = 3;
$actions[$target]("张三"); // 自动找到 3 号卡片执行

$target = 4;
$actions[$target]("李四"); // 自动找到 4 号卡片执行
